from __future__ import annotations

from typing import Sequence

from ..declares import FEATURE_VECTOR, FLOAT
from .TileCode import TileCode


class TileCodeCorrect(TileCode):
    """The recommended implementation of tile coding for medium size state-space.

    Called "correct" since feature vectors are generated by careful offsetting,
    ensuring they are unique, in contrast to hashing alternatives where
    collisions can occur. Although correct, it consumes more space than the
    hashing alternatives, making it impractical for high dimensional spaces.
    """

    def getFeatureVector(self, parameters: Sequence[FLOAT]) -> FEATURE_VECTOR:
        fv: FEATURE_VECTOR = [0] * self.getNumTilings()
        for i in range(self.getNumTilings()):
            # x1 + x2*x1.gridSize + x3*x1.gridSize*x2.gridSize + ...
            hashedIndex = 0
            mult = 1
            for j in range(self.getDimension()):
                hashedIndex += self.paramToGridValue(parameters[j], i, j) * mult
                mult *= self._dimensionalInfos[j].GetGridCountReal()
            hashedIndex += mult * i
            assert hashedIndex <= self._sizeCache, (
                "Size cache exceeded. Illegal feature vector value."
            )
            fv[i] = hashedIndex
        return fv
