from __future__ import annotations

from typing import Any, Generic, List, Sequence, TypeVar

try:
    from .TileCode import TileCode, DEFAULT_TILE_CONT
except (ImportError, ValueError):
    try:
        from TileCode import TileCode, DEFAULT_TILE_CONT
    except (ImportError, ValueError):
        DEFAULT_TILE_CONT = List[float]  # type: ignore

        class TileCode(Generic[Any, Any, Any]):  # type: ignore
            pass

D = TypeVar("D")
NUM_TILINGS = TypeVar("NUM_TILINGS")
WEIGHT_CONT = TypeVar("WEIGHT_CONT")

FEATURE_VECTOR = List[int]
floatArray = Sequence[float]


class TileCodeCorrect(TileCode[D, NUM_TILINGS, WEIGHT_CONT]):
    """The recommended implementation of Tile Coding for medium size state-space.

    This is called TileCodeCorrect, since feature vector are generated by careful
    offsetting ensuring the feature vectors are unique, in contrast to hashing alternatives
    in which there might be a collision thus feature vectors might not be unique. Although
    it is correct, it consumes more space than hashing alternative, making it impractical
    for high dimensional state-spaces.

    :param D: Number of dimension.
    :param NUM_TILINGS: Number of tilings.
    :param WEIGHT_CONT: The container object to store the weights.
    """

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)

    def getFeatureVector(self, parameters: Sequence[float]) -> FEATURE_VECTOR:
        num_tilings = (
            self.getNumTilings()
            if hasattr(self, "getNumTilings")
            else self.get_num_tilings()
        )
        fv: FEATURE_VECTOR = [0] * num_tilings

        dimension = (
            self.getDimension()
            if hasattr(self, "getDimension")
            else self.get_dimension()
        )
        grid_fn = (
            self.paramToGridValue
            if hasattr(self, "paramToGridValue")
            else self.param_to_grid_value
        )
        dim_infos = (
            self._dimensionalInfos
            if hasattr(self, "_dimensionalInfos")
            else getattr(self, "_dimensional_infos", self._dimensionalInfos)
        )
        size_cache = (
            self._sizeCache
            if hasattr(self, "_sizeCache")
            else getattr(self, "_size_cache", self._sizeCache)
        )

        for i in range(num_tilings):
            # x1 + x2*x1.gridSize + x3*x1.gridSize*x2.gridSize + ...
            hashed_index = 0
            mult = 1
            for j in range(dimension):
                hashed_index += grid_fn(parameters[j], i, j) * mult
                dim_info = dim_infos[j]
                grid_count = (
                    dim_info.GetGridCountReal()
                    if hasattr(dim_info, "GetGridCountReal")
                    else dim_info.get_grid_count_real()
                )
                mult *= grid_count

            hashed_index += mult * i
            assert hashed_index <= size_cache, (
                "Size cache exceeded. Illegal feature vector value."
            )
            fv[i] = hashed_index

        return fv

    get_feature_vector = getFeatureVector